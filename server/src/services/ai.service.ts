import { GoogleGenerativeAI } from '@google/generative-ai';
import OpenAI from 'openai';
import { prisma } from '../prisma';
import { config } from '../config';
import { paypalService } from './paypal.service';
import { analyticsService } from './analytics.service';

export interface AgentActionPayload {
  type: string;
  title: string;
  description: string;
  data: any;
  confirmActionEndpoint?: string;
}

export interface AgentResponse {
  message: string;
  toolExecuted?: string;
  toolResult?: any;
  requiresConfirmation?: boolean;
  pendingAction?: AgentActionPayload;
}

export class AiAgentService {
  /**
   * Tool 1: Create Invoice (Draft + PayPal sync)
   */
  public async toolCreateInvoice(userId: string, params: {
    customerName: string;
    customerEmail?: string;
    amount: number;
    description: string;
    dueDays?: number;
    notes?: string;
  }) {
    // 1. Find or create customer
    let customer = await prisma.customer.findFirst({
      where: {
        userId,
        name: { contains: params.customerName }
      }
    });

    if (!customer) {
      customer = await prisma.customer.create({
        data: {
          userId,
          name: params.customerName,
          email: params.customerEmail || `${params.customerName.toLowerCase().replace(/\s+/g, '.')}@example.com`,
          company: `${params.customerName} Co.`,
          notes: 'Created automatically by PayPilot AI Agent'
        }
      });
    }

    const dueDays = params.dueDays || 7;
    const dueDate = new Date(Date.now() + dueDays * 24 * 60 * 60 * 1000);
    const count = await prisma.invoice.count({ where: { userId } });
    const invoiceNumber = `INV-${new Date().getFullYear()}-${String(count + 1).padStart(3, '0')}`;

    return {
      status: 'PREPARED',
      invoiceNumber,
      customerId: customer.id,
      customerName: customer.name,
      customerEmail: customer.email,
      description: params.description,
      amount: params.amount,
      dueDate: dueDate.toISOString(),
      dueDays,
      notes: params.notes || 'Generated by PayPilot AI'
    };
  }

  /**
   * Commit confirmed invoice to DB and PayPal Sandbox Invoicing API
   */
  public async commitInvoice(userId: string, preparedData: any) {
    let paypalInvoiceId: string | null = null;
    let paypalInvoiceUrl: string | null = null;

    // Check if PayPal Sandbox is configured
    if (paypalService.isConfigured()) {
      try {
        const ppInv = await paypalService.createInvoice({
          invoiceNumber: preparedData.invoiceNumber,
          customerName: preparedData.customerName,
          customerEmail: preparedData.customerEmail,
          dueDate: preparedData.dueDate.split('T')[0],
          items: [{
            description: preparedData.description,
            quantity: 1,
            unitPrice: preparedData.amount
          }],
          notes: preparedData.notes
        });
        paypalInvoiceId = ppInv.paypalInvoiceId;
        paypalInvoiceUrl = ppInv.viewUrl;
      } catch (err: any) {
        console.warn('PayPal Invoicing API call note:', err.message);
      }
    }

    const invoice = await prisma.invoice.create({
      data: {
        invoiceNumber: preparedData.invoiceNumber,
        userId,
        customerId: preparedData.customerId,
        status: paypalInvoiceId ? 'SENT' : 'UNPAID',
        issueDate: new Date(),
        dueDate: new Date(preparedData.dueDate),
        currency: 'USD',
        subtotal: preparedData.amount,
        tax: 0,
        total: preparedData.amount,
        notes: preparedData.notes,
        paypalInvoiceId,
        paypalInvoiceUrl,
        items: {
          create: [
            {
              description: preparedData.description,
              quantity: 1,
              unitPrice: preparedData.amount,
              amount: preparedData.amount
            }
          ]
        }
      },
      include: {
        customer: true,
        items: true
      }
    });

    return invoice;
  }

  /**
   * Tool 2: Create Payment Request with PayPal checkout order
   */
  public async toolCreatePaymentRequest(userId: string, params: {
    customerName: string;
    amount: number;
    description: string;
  }) {
    let customer = await prisma.customer.findFirst({
      where: {
        userId,
        name: { contains: params.customerName }
      }
    });

    if (!customer) {
      customer = await prisma.customer.create({
        data: {
          userId,
          name: params.customerName,
          email: `${params.customerName.toLowerCase().replace(/\s+/g, '.')}@example.com`,
          company: `${params.customerName} Enterprise`
        }
      });
    }

    let paypalOrderId: string | null = null;
    let paypalCheckoutUrl: string | null = null;

    if (paypalService.isConfigured()) {
      try {
        const order = await paypalService.createOrder({
          amount: params.amount,
          description: params.description,
          customerEmail: customer.email
        });
        paypalOrderId = order.id;
        const approveLink = order.links?.find((l: any) => l.rel === 'approve')?.href;
        paypalCheckoutUrl = approveLink || null;
      } catch (err: any) {
        console.warn('PayPal Order API note:', err.message);
      }
    }

    const pr = await prisma.paymentRequest.create({
      data: {
        userId,
        customerId: customer.id,
        amount: params.amount,
        currency: 'USD',
        description: params.description,
        status: 'PENDING',
        paypalOrderId,
        paypalCheckoutUrl
      },
      include: {
        customer: true
      }
    });

    return {
      paymentRequestId: pr.id,
      customerName: customer.name,
      customerEmail: customer.email,
      amount: pr.amount,
      description: pr.description,
      checkoutUrl: `/pay/${pr.id}`,
      paypalOrderId: pr.paypalOrderId
    };
  }

  /**
   * Tool 3: Get Unpaid and Overdue Invoices
   */
  public async toolGetUnpaidInvoices(userId: string, overdueOnly = false) {
    const now = new Date();
    const invoices = await prisma.invoice.findMany({
      where: {
        userId,
        status: overdueOnly ? 'OVERDUE' : { in: ['UNPAID', 'SENT', 'OVERDUE'] }
      },
      include: { customer: true },
      orderBy: { dueDate: 'asc' }
    });

    return invoices.map(i => {
      const isPastDue = new Date(i.dueDate) < now;
      const daysOverdue = isPastDue ? Math.floor((now.getTime() - new Date(i.dueDate).getTime()) / (1000 * 60 * 60 * 24)) : 0;
      return {
        id: i.id,
        invoiceNumber: i.invoiceNumber,
        customerName: i.customer.name,
        company: i.customer.company,
        amount: i.total,
        dueDate: i.dueDate.toISOString().split('T')[0],
        status: isPastDue ? 'OVERDUE' : i.status,
        daysOverdue,
        paypalInvoiceId: i.paypalInvoiceId
      };
    });
  }

  /**
   * Tool 4: Identify Overdue Customers and Payment Delay Analysis
   */
  public async toolIdentifyOverdueCustomers(userId: string) {
    const analysis = await analyticsService.getCustomerDelayAnalysis(userId);
    return analysis.filter(c => c.overdueCount > 0);
  }

  /**
   * Tool 5: Generate Financial Report for Current / Specified Month
   */
  public async toolGenerateFinancialReport(userId: string) {
    const overview = await analyticsService.getFinancialOverview(userId);
    const revenueAnalytics = await analyticsService.getRevenueAnalytics(userId);
    const topCustomers = await analyticsService.getCustomerDelayAnalysis(userId);

    const payingAccounts = topCustomers
      .filter(c => c.totalPaidAmount > 0)
      .sort((a, b) => b.totalPaidAmount - a.totalPaidAmount)
      .slice(0, 3);

    return {
      month: new Date().toLocaleDateString('en-US', { month: 'long', year: 'numeric' }),
      totalRevenue: overview.totalRevenue,
      revenueLast30Days: overview.revenueLast30Days,
      growthRate: overview.monthlyGrowthRate,
      pendingAmount: overview.pendingAmount,
      overdueAmount: overview.overdueAmount,
      completedTransactionsCount: overview.totalPaymentsReceived,
      topPayingCustomers: payingAccounts.map(p => ({
        name: p.name,
        company: p.company,
        totalPaid: p.totalPaidAmount
      })),
      invoiceStatusBreakdown: revenueAnalytics.statusCounts,
      observations: [
        `Revenue trajectory is ${overview.monthlyGrowthRate >= 0 ? '+' : ''}${overview.monthlyGrowthRate}% relative to the previous 30-day window.`,
        `Settled ${overview.totalPaymentsReceived} transactions through verified PayPal orders.`,
        overview.overdueAmount > 0 
          ? `Outstanding debt of $${overview.overdueAmount.toLocaleString()} requires proactive attention.`
          : 'Zero overdue balances detected across all accounts.'
      ]
    };
  }

  /**
   * Tool 6: Draft Payment Reminder for Overdue Invoice
   */
  public async toolDraftPaymentReminder(userId: string, customerName?: string) {
    const overdueList = await this.toolGetUnpaidInvoices(userId, true);
    let target = overdueList[0];
    if (customerName) {
      const match = overdueList.find(i => i.customerName.toLowerCase().includes(customerName.toLowerCase()));
      if (match) target = match;
    }

    if (!target) {
      return { message: 'No overdue invoices currently require reminders.' };
    }

    const emailSubject = `Friendly Reminder: Invoice ${target.invoiceNumber} for ${target.customerName}`;
    const emailBody = `Dear ${target.customerName},\n\nWe hope this email finds you well.\n\nThis is a polite reminder that invoice ${target.invoiceNumber} for $${target.amount.toFixed(2)} was due on ${target.dueDate} (${target.daysOverdue} days ago).\n\nYou can remit payment directly through our secure PayPal portal using the link below:\n${config.clientUrl}/pay/invoice/${target.id}\n\nThank you for your prompt attention.\n\nBest regards,\nAlex Morgan\nNexus Cloud Solutions`;

    return {
      invoiceId: target.id,
      invoiceNumber: target.invoiceNumber,
      customerName: target.customerName,
      amount: target.amount,
      daysOverdue: target.daysOverdue,
      subject: emailSubject,
      body: emailBody
    };
  }

  /**
   * Main Agent Execution Gateway:
   * Interprets user prompt via Gemini/OpenAI or Intelligent Fallback NLP
   */
  public async processUserMessage(userId: string, prompt: string): Promise<AgentResponse> {
    const p = prompt.trim();
    const pLower = p.toLowerCase();

    // 1. Check for Invoice Creation intent (e.g. "Create an invoice for Sarah for $750 for graphic design services, due in 7 days.")
    if (
      pLower.includes('invoice') && 
      (pLower.includes('create') || pLower.includes('make') || pLower.includes('generate') || pLower.includes('send') || pLower.includes('draft') || pLower.includes('bill'))
    ) {
      // Regex parsing for name, amount, service, due days
      const amountMatch = p.match(/\$(\d+([.,]\d+)?)/) || p.match(/(\d+)\s*(dollars|usd)/i);
      const amount = amountMatch ? parseFloat(amountMatch[1].replace(/,/g, '')) : 500;

      // Extract customer name (e.g., "for Sarah", "to John", "for Johnathan Vance")
      const nameMatch = p.match(/(?:for|to)\s+([A-Z][a-z]+(?:\s+[A-Z][a-z]+)?)/) || p.match(/(?:for|to)\s+([a-zA-Z]+)/);
      const customerName = nameMatch ? nameMatch[1] : 'Valued Client';

      // Extract service description (e.g., "for website development", "for graphic design services")
      let description = 'Professional Services';
      const descMatch = p.match(/for\s+(?!Sarah|Michael|John|Elena|David|\$|\d+)([^,.]+?)(?:,|\.|\s+due|\s+in|$)/i);
      if (descMatch && descMatch[1].trim().length > 3) {
        description = descMatch[1].trim();
      }

      // Extract due days
      const daysMatch = p.match(/(\d+)\s*days?/i);
      const dueDays = daysMatch ? parseInt(daysMatch[1], 10) : 7;

      const prepared = await this.toolCreateInvoice(userId, {
        customerName,
        amount,
        description,
        dueDays
      });

      return {
        message: `I have prepared the invoice draft for **${customerName}** for **$${amount.toLocaleString()}**. Please review the details below and confirm to generate the invoice and sync with PayPal.`,
        toolExecuted: 'create_invoice',
        requiresConfirmation: true,
        pendingAction: {
          type: 'CONFIRM_INVOICE_CREATION',
          title: `Create Invoice for ${customerName} ($${amount})`,
          description: `Invoice ${prepared.invoiceNumber}: ${description} (${dueDays} days due term)`,
          data: prepared,
          confirmActionEndpoint: '/api/ai/confirm-action'
        }
      };
    }

    // 2. Check for Payment Request intent (e.g. "Request $300 from Michael for consulting")
    if (pLower.includes('request') && (pLower.includes('$') || pLower.includes('dollar') || pLower.includes('payment'))) {
      const amountMatch = p.match(/\$(\d+([.,]\d+)?)/) || p.match(/(\d+)\s*(dollars|usd)/i);
      const amount = amountMatch ? parseFloat(amountMatch[1].replace(/,/g, '')) : 250;

      const nameMatch = p.match(/(?:from|to|for)\s+([A-Z][a-z]+(?:\s+[A-Z][a-z]+)?)/i);
      const customerName = nameMatch ? nameMatch[1] : 'Michael Chen';

      let description = 'Consulting retainer';
      const descMatch = p.match(/for\s+([^,.]+)/i);
      if (descMatch && !descMatch[1].includes('$')) {
        description = descMatch[1].trim();
      }

      const pr = await this.toolCreatePaymentRequest(userId, {
        customerName,
        amount,
        description
      });

      return {
        message: `I've generated a payment request for **${customerName}** for **$${amount.toFixed(2)}** (${description}).\n\nThe customer can complete the payment directly via PayPal Sandbox:`,
        toolExecuted: 'create_payment_request',
        toolResult: pr
      };
    }

    // 3. Check for Overdue / Unpaid Invoices query (e.g. "Show me all unpaid invoices", "Which customers have overdue payments?")
    if (pLower.includes('unpaid') || pLower.includes('overdue') || pLower.includes('pending payment')) {
      const isOverdue = pLower.includes('overdue') || pLower.includes('late');
      const invoices = await this.toolGetUnpaidInvoices(userId, isOverdue);
      const totalOutstanding = invoices.reduce((s, i) => s + i.amount, 0);

      return {
        message: isOverdue 
          ? `I identified **${invoices.length} overdue invoice(s)** totaling **$${totalOutstanding.toLocaleString()}**:` 
          : `You currently have **${invoices.length} unpaid/pending invoice(s)** totaling **$${totalOutstanding.toLocaleString()}**:`,
        toolExecuted: isOverdue ? 'identify_overdue_customers' : 'get_unpaid_invoices',
        toolResult: { invoices, totalOutstanding }
      };
    }

    // 4. Check for Late Payers / Delayed Customer Analysis (e.g. "Which customers have delayed payments most frequently?")
    if (pLower.includes('delay') || pLower.includes('frequently pay late') || pLower.includes('risk') || pLower.includes('late pay')) {
      const overdueCustomers = await this.toolIdentifyOverdueCustomers(userId);
      return {
        message: `Based on actual invoice transaction history, here is the payment delay analysis for your customer accounts:`,
        toolExecuted: 'analyze_customer_payments',
        toolResult: overdueCustomers
      };
    }

    // 5. Check for Monthly Financial Report (e.g. "Generate my monthly financial report", "Show me my revenue for the last 30 days")
    if (pLower.includes('report') || pLower.includes('revenue') || pLower.includes('financial') || pLower.includes('30 days')) {
      const report = await this.toolGenerateFinancialReport(userId);
      return {
        message: `Here is your verified **Financial Operations Report for ${report.month}**, computed directly from settled PayPal transactions:`,
        toolExecuted: 'generate_financial_report',
        toolResult: report
      };
    }

    // 6. Check for Payment Reminders (e.g. "Show me customers who need payment reminders")
    if (pLower.includes('reminder') || pLower.includes('remind')) {
      const reminder = await this.toolDraftPaymentReminder(userId);
      return {
        message: `I have drafted a polite payment reminder for overdue invoice **${(reminder as any).invoiceNumber}** for **${(reminder as any).customerName}**:`,
        toolExecuted: 'draft_payment_reminder',
        toolResult: reminder
      };
    }

    // 7. General Financial Q&A with Gemini / OpenAI fallback
    if (config.ai.geminiApiKey) {
      try {
        const genAI = new GoogleGenerativeAI(config.ai.geminiApiKey);
        const model = genAI.getGenerativeModel({ model: 'gemini-1.5-flash' });
        const overview = await analyticsService.getFinancialOverview(userId);
        const promptContext = `You are PayPilot, an expert AI financial operations assistant for PayPal. The user's business overview: Total Revenue $${overview.totalRevenue}, Pending $${overview.pendingAmount}, Overdue $${overview.overdueAmount}, Growth ${overview.monthlyGrowthRate}%. Respond concisely and professionally in markdown: ${prompt}`;
        const result = await model.generateContent(promptContext);
        return {
          message: result.response.text()
        };
      } catch (err: any) {
        console.warn('Gemini API fallback triggered:', err.message);
      }
    }

    // Default polite helpful response with command suggestions
    return {
      message: `I can help you manage your business finances with PayPal. Try asking me:
- *"Create an invoice for Sarah for $750 for graphic design services, due in 7 days."*
- *"Request $300 from Michael for consulting."*
- *"Show me all unpaid invoices."*
- *"Which customers have overdue payments?"*
- *"Generate my monthly financial report."*`
    };
  }
}

export const aiService = new AiAgentService();
